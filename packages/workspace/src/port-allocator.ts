import * as fs from 'node:fs';
import * as net from 'node:net';
import * as path from 'node:path';

export interface WorktreePortAllocation {
  worktreeId: string;
  basePort: number;
  apiPort: number;
  dbPort: number;
  offset: number;
  env: Record<string, string>;
}

const PORT_BLOCK_STRIDE = 10;
const BASE_START_PORT = 4100;
const MAX_PORT = 59000;

/** Checks whether a TCP port is currently free on 127.0.0.1. */
export function isPortAvailable(port: number): Promise<boolean> {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.unref();
    server.once('error', () => resolve(false));
    server.once('listening', () => {
      server.close(() => resolve(true));
    });
    server.listen(port, '127.0.0.1');
  });
}

/**
 * Allocates collision-free ephemeral port blocks (`TASKFORGE_PORT`,
 * `TASKFORGE_API_PORT`, `TASKFORGE_DB_PORT`, `PORT`) per parallel worktree so
 * concurrent dev servers and integration test suites never collide on
 * `localhost:3000` or `localhost:5432`.
 */
export class WorktreePortAllocator {
  private readonly allocated = new Map<string, WorktreePortAllocation>();
  private readonly reservedPorts = new Set<number>();

  public async allocate(
    worktreeId: string,
    worktreePath?: string,
  ): Promise<WorktreePortAllocation> {
    const existing = this.allocated.get(worktreeId);
    if (existing) return existing;

    for (let base = BASE_START_PORT; base + 3 < MAX_PORT; base += PORT_BLOCK_STRIDE) {
      const ports = [base, base + 1, base + 2];
      if (ports.some((p) => this.reservedPorts.has(p))) continue;

      const checks = await Promise.all(ports.map((p) => isPortAvailable(p)));
      if (!checks.every(Boolean)) continue;

      for (const p of ports) this.reservedPorts.add(p);
      const offset = base - BASE_START_PORT;
      const env: Record<string, string> = {
        PORT: String(base),
        TASKFORGE_PORT: String(base),
        TASKFORGE_API_PORT: String(base + 1),
        TASKFORGE_DB_PORT: String(base + 2),
        TASKFORGE_PORT_OFFSET: String(offset),
      };
      const alloc: WorktreePortAllocation = {
        worktreeId,
        basePort: base,
        apiPort: base + 1,
        dbPort: base + 2,
        offset,
        env,
      };
      this.allocated.set(worktreeId, alloc);

      if (worktreePath && fs.existsSync(worktreePath)) {
        try {
          const envContent = [
            '# Auto-generated by TaskForge WorktreePortAllocator (git-excluded)',
            ...Object.entries(env).map(([k, v]) => `${k}=${v}`),
            '',
          ].join('\n');
          fs.writeFileSync(path.join(worktreePath, '.taskforge.env'), envContent, 'utf8');
        } catch {
          // best-effort
        }
      }

      return alloc;
    }

    throw new Error('WorktreePortAllocator: no free ephemeral port block available.');
  }

  public release(worktreeId: string): void {
    const alloc = this.allocated.get(worktreeId);
    if (!alloc) return;
    this.reservedPorts.delete(alloc.basePort);
    this.reservedPorts.delete(alloc.apiPort);
    this.reservedPorts.delete(alloc.dbPort);
    this.allocated.delete(worktreeId);
  }

  public get(worktreeId: string): WorktreePortAllocation | undefined {
    return this.allocated.get(worktreeId);
  }

  public list(): WorktreePortAllocation[] {
    return [...this.allocated.values()];
  }
}
